package practice;

public class Kurohon7shou implements Q7_7If, Q7_7If2 {

	public static void main(String[] args) {
		
		//インターフェースは「機能の部品セット」として使います。
		//たとえば「飛べる」「泳げる」などの“能力”を別のクラスに追加するイメージ。
		//インターフェースに書かれたメソッドは処理を持たず、**実装するクラスで中身を書く（オーバーライド）**のがルール。
		//インターフェースに書かれるメソッドは、**原則すべて抽象メソッド（中身がない）**です。
		//※ただし default メソッドなどは中身を持てます（Q7_4_Interfaceの中身に記述してある）
		//クラスは１つしか継承できないが、インターフェースは複数実装することが可能。
		
		//この設問では、基本は実装しているQ7_4_Subで中身を決めなければならないが、
		//defaultで修飾しているメソッドしかないため空となっている。
		Q7_4If s7_4 = new Q7_4Sub();
		s7_4.sample7_4();
		
		
		//大元のメソッドを呼び出す方法。
		//superの使い方。Q7_6Subを参照
		Q7_6If s7_6 = new Q7_6Sub();
		s7_6.greet();
		
		
		
		//設問7_7
		//2つのインターフェースを実装するが、同じ名前のメソッドがあった場合どうするか。
		//下部テストメソッドのように、superを使いどちらを使うかを定義しなければならない。
		new Kurohon7shou().test();
		
		
		//抽象クラスの継承問題。
		//抽象クラス自体は new できないが、抽象メソッドをすべて実装したサブクラスを new するのは OK。
		//【補足】以下のインスタンス化は、
		//「親クラスの型でサブクラスのインスタンスを扱う」という典型的な**ポリモーフィズム（多態性）**
		//親クラスのメソッドしか使えないが、オーバーライドされているものならサブクラスから呼ばれる
		Q7_9oya s7_9 = new Q7_9Sub();
		s7_9.sample();
		
		//【補足続き】
		//以下はサブクラスでインスタンス化。これは抽象メソッドが解決されているので、普通のメソッドと同じ
		//親クラスとサブクラスのすべての public/protected メソッドが使える
		//※privateで抽象メソッドは作れない（コンパイルエラー）
		//privateフィールドなどが定義されていたら、ゲッターセッターを親クラスで実装するべき。
		Q7_9Sub s7_92 = new Q7_9Sub();
		s7_92.sample();
		
		
		//オーバーライドルール
		//①シグニチャが同じであること（引数リストの定義は、型、数、順順番のすべてが同じ）
		//②戻り値型は同じ型か、サブクラスで定義した型であること
		//③アクセス修飾子は同じか、より緩いものであること
		
		
		//以下はサブクラスにてoyaをsubに上書きしているが、すべてoyaが表示されるもの。
		//フィールド（変数）は「型で決まる」
		//メソッド（関数）は「**実体（newしたクラス）で決まる」
		//もしサブを表示したいのなら、インスタンス化の元をoyaではなくsubにすることと、サブクラスでオーバーライドすればOK
		Q7_12oya a7_12 = new Q7_12oya();
		Q7_12oya b7_12 = new Q7_12Sub();
		System.out.print(a7_12.val);  //フィールド：Q7_12oya型 → 親の変数
		System.out.print(b7_12.val);  //フィールド：Q7_12oya型 → 親の変数
		a7_12.print();                //メソッド：親の print() を実行
		b7_12.print();                //メソッド：実体は子でも、printは親のもの 
		System.out.println();
		
		
		
		
		//7_15
		//配列の問題。
		//この場合、それぞれが親子関係か、
		//インスタンス化するオブジェクトがインターフェースや抽象クラスではないかなどが大事
		
		
		//7_16
		//アップキャスト = 子クラス型のオブジェクトを親クラス型に変換すること
		//自動で変換される（キャスト式は不要）
		//ダウンキャスト = 親クラス型のオブジェクトを子クラス型に変換すること
		//明示的なキャストが必要（(子クラス型)を書く）
		//キャスト式：変換後の型 変数名 = (変換後の型) 変数名または値;
		//int num = (int) 3.14        // キャストして「3」
		//Dog dog1 = (Dog) animal      // オブジェクトのキャスト
		Q7_16oya s7_16 = new Q7_16Sub();    //これは1行であらわしたアップキャスト
		Q7_16Sub s7_162 = (Q7_16Sub) s7_16; //ダウンキャスト。s7_16をsub型に変換している
		s7_162.hello();
		
		//※【注意】キャストは変数の型を変えるだけ。中身は変わらない
		try {
		Q7_16oya s7_163 = new Q7_16oya(); 
		Q7_16Sub s7_164 = (Q7_16Sub) s7_163;
		}catch (Exception e) {
			System.out.println("oya型(中身もoya)なのにBになろうとしていることエラー。85行目みたいに中身がSubならOk");
		}
		
		
		//引数なしコンストラクタと引数ありコンストラクタの動き方問題。
		//this(); = コンストラクタでしかつかえない特殊な構文。
		//コンストラクタの呼び出しに使う。()に引数を入れて、引数ありのコンストラクタを指定もできる。
		//なお、コンストラクタ内の1行目に記述しないとだめ。
		//流れ⇒引数ありでSubをインスタンス化
		//① Q7_21Sub(String val) が呼ばれる
		//② Q7_21Sub() が呼ばれる（this(); の効果）
		//③ Q7_21oya(String val) が呼ばれる（super("B") により）
		//④ Q7_21oya() が呼ばれる（this(); の効果）
		new Q7_21Sub("?");
		System.out.println();

			
	}
	
	//7_7テストメソッド
	@Override
	public void test() {
		Q7_7If2.super.test();
	}

}
